import assert from 'node:assert/strict';
import {validateConstruction} from './scripts/construction-rules.mjs';
import {validateStations} from './scripts/station-rules.mjs';
const types=['Pilot’s Console','Generator','Gunnery','Scanners','Magic Conduit','Pilot’s Console'];
const base={level:6,crewQuarters:'Bunks',passengerQuarters:'Basic',baySlots:['Unassigned','Unassigned','Unassigned','Unassigned'],stationBuilds:types.map(type=>({type,capacity:10,upgrades:[]}))};
assert.deepEqual(validateConstruction(base),[]);
const wrong=structuredClone(base);wrong.stationBuilds[0].upgrades=[{id:'pulse-shield',grade:'commercial'}];
assert(validateStations(wrong).some(x=>x.code==='WRONG_STATION'));
const duplicate=structuredClone(base);duplicate.stationBuilds[1].upgrades=[{id:'pulse-shield',grade:'commercial'},{id:'pulse-shield',grade:'commercial'}];
assert(validateStations(duplicate).some(x=>x.code==='DUPLICATE_UPGRADE'));
const level=structuredClone(base);level.stationBuilds[1].upgrades=[{id:'pulse-shield',grade:'advanced'}];
assert(validateStations(level).some(x=>x.code==='UPGRADE_LEVEL'));
const over=structuredClone(base);over.baySlots.push('Science Lab');
assert(validateConstruction(over).some(x=>x.code==='BAY_CAPACITY'));
const comfort=structuredClone(over);comfort.crewQuarters='Comfortable';
assert(!validateConstruction(comfort).some(x=>x.code==='BAY_CAPACITY'));
console.log('Six construction regression tests passed.');
import {FRAME_STATS,SENSOR_BASE} from './scripts/frame-data.mjs';
import {applyFrameStats,applyIncomingDamage,validateOverride} from './scripts/ship-state.mjs';
import {WEAPONS,ESCAPE_PODS} from './scripts/equipment-data.mjs';
assert.equal(Object.keys(FRAME_STATS).length,3);
for(const frame of Object.keys(FRAME_STATS))assert.equal(Object.keys(FRAME_STATS[frame]).length,20);
assert.equal(WEAPONS.length,17);
assert.equal(ESCAPE_PODS.length,6);
const explorer=FRAME_STATS.Explorer['6'];
assert.equal(explorer.hpMax,90);assert.equal(explorer.spMax,42);
const hurt={...base,frame:'Explorer',escapePod:'Standard',stationBuilds:structuredClone(base.stationBuilds)};
hurt.stationBuilds[1].upgrades=[{id:'pulse-shield',grade:'commercial'}];
assert(!validateConstruction(hurt).some(x=>x.code==='DEFAULT_EQUIPMENT'));
const weaponError=structuredClone(hurt);weaponError.stationBuilds[2].weapons=['Light laser cannon','Fragment launcher'];
assert(validateConstruction(weaponError).some(x=>x.code==='GUNNERY_WEAPONS'));
weaponError.stationBuilds[2].upgrades=[{id:'secondary-armaments'}];
assert(!validateConstruction(weaponError).some(x=>x.code==='GUNNERY_WEAPONS'));
const podError=structuredClone(hurt);podError.escapePod='Telepod';
assert(validateConstruction(podError).some(x=>x.code==='ESCAPE_POD_LEVEL'));
const ship={hpMax:90,hp:60,spMax:42,sp:20,sensors:8,sensorBase:6};
const grown=applyFrameStats(ship,{hpMax:100,spMax:50,ac:22},6);
assert.equal(grown.hp,70);assert.equal(grown.sp,28);assert.equal(grown.sensors,8);
const damaged=applyIncomingDamage({hp:80,sp:10},18);
assert.equal(damaged.hp,72);assert.equal(damaged.sp,0);
assert.equal(validateOverride([{code:'X'}],{gmOverride:true,overrideReason:'Story ship'},true).ok,true);
assert.equal(validateOverride([{code:'X'}],{gmOverride:true,overrideReason:''},true).ok,false);
console.log('Additional frame, equipment, damage and GM override tests passed.');
